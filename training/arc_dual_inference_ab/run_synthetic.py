#!/usr/bin/env python3
"""Pairwise synthetic scheduler benchmark. No model, network, or GPU calls."""
from __future__ import annotations
import argparse
import asyncio
import hashlib
import json
import random
import statistics
import time
from datetime import datetime, timezone
from pathlib import Path


def scenario(seed: int, case_id: str) -> dict[str, int]:
    rng = random.Random(f"{seed}:{case_id}")
    return {"draft_ms": rng.randint(18, 28), "verify_ms": rng.randint(32, 48),
            "evidence_lane_ms": rng.randint(38, 58), "connection_lane_ms": rng.randint(42, 64),
            "director_ms": rng.randint(10, 16), "trs_ms": rng.randint(4, 8)}

async def delay(ms: int) -> None:
    await asyncio.sleep(ms / 1000)

async def run_case(case: dict, seed: int, trs: bool) -> dict:
    d = scenario(seed, case["id"])
    t0 = time.perf_counter()
    # A: serial draft -> verify; category controls draft budget, TRS is isolated.
    await delay(d["draft_ms"])
    await delay(d["verify_ms"])
    if trs:
        await delay(d["trs_ms"])
    a_wall = (time.perf_counter() - t0) * 1000
    a_model = d["draft_ms"] + d["verify_ms"] + (d["trs_ms"] if trs else 0)

    t1 = time.perf_counter()
    # B: independent deductive/evidence and connection/impact streams + director.
    await asyncio.gather(delay(d["evidence_lane_ms"]), delay(d["connection_lane_ms"]))
    await delay(d["director_ms"])
    b_wall = (time.perf_counter() - t1) * 1000
    b_model = max(d["evidence_lane_ms"], d["connection_lane_ms"]) + d["director_ms"]
    return {"case_id": case["id"], "category": case["category"], "seed": seed,
            "A_category_adaptive": {"modelled_latency_ms": a_model, "scheduler_wall_ms": round(a_wall, 2), "trs_enabled": trs},
            "B_deductive_connection": {"modelled_latency_ms": b_model, "scheduler_wall_ms": round(b_wall, 2), "path_count": 2},
            "quality": "not_measured; outputs are not generated by a language model"}

async def main(args) -> dict:
    cases_path = Path(__file__).parent / "cases" / "cases.json"
    cases = json.loads(cases_path.read_text())
    results = []
    for seed in range(args.runs):
        for case in cases:
            results.append(await run_case(case, seed, args.trs))
    a = [r["A_category_adaptive"]["modelled_latency_ms"] for r in results]
    b = [r["B_deductive_connection"]["modelled_latency_ms"] for r in results]
    payload = {"benchmark_id": "arc-dual-inference-synthetic-v1", "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "runs_per_case": args.runs, "paired_observations": len(results), "trs_enabled_in_A": args.trs,
        "latency_kind": "synthetic modelled component delays; scheduler wall time also reported but is not inference latency",
        "quality_status": "not_measured", "weights_changed": False, "network_calls": 0, "gpu_calls": 0,
        "input_cases_sha256": hashlib.sha256(cases_path.read_bytes()).hexdigest(),
        "summary": {"A_modelled_mean_ms": round(statistics.mean(a), 2), "B_modelled_mean_ms": round(statistics.mean(b), 2),
                    "paired_mean_B_minus_A_ms": round(statistics.mean(y-x for x,y in zip(a,b)), 2)},
        "observations": results}
    if args.json:
        Path(args.json).write_text(json.dumps(payload, indent=2) + "\n")
    print(json.dumps({k:v for k,v in payload.items() if k != "observations"}, indent=2))
    return payload

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs", type=int, default=20)
    parser.add_argument("--trs", action="store_true", help="include synthetic tie-breaker cost in A")
    parser.add_argument("--json", help="write run record")
    options = parser.parse_args()
    if options.runs < 1 or options.runs > 1000:
        parser.error("--runs must be between 1 and 1000")
    asyncio.run(main(options))
